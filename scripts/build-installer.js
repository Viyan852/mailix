#!/usr/bin/env node

/**
 * MAILIX Windows Installer Builder
 *
 * Produces MAILIX-Setup-x64.exe using NSIS (Nullsoft Scriptable Install
 * System). The installer is per-user (no admin required), installs to
 * %LOCALAPPDATA%\MAILIX, bundles the Node.js runtime and the MAILIX icon,
 * creates Start Menu and Desktop shortcuts, and updates the user PATH
 * idempotently.
 *
 * Critical safety properties (hardened in this version):
 *   1. Uninstall NEVER removes user data (config, data, logs, backups).
 *      Only the application files, runtime, and installer are removed.
 *   2. PATH registration is idempotent — running the installer twice does
 *      not create duplicate entries.
 *   3. PATH removal on uninstall is also idempotent and safe.
 *   4. The icon is the only authoritative icon source (assets/icon.ico).
 *
 * Usage:
 *   node scripts/build-installer.js --platform=windows-x64
 *                                --in dist/build/mailix-windows-x64-v2.0.0
 *                                --out dist
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);

function getArg(name, fallback) {
  const a = args.find(x => x.startsWith(`--${name}=`));
  return a ? a.split('=').slice(1).join('=') : fallback;
}

const inDir = path.resolve(getArg('in', path.join(ROOT, 'dist', 'build')));
const outDir = path.resolve(getArg('out', path.join(ROOT, 'dist')));
const platform = getArg('platform', 'windows-x64');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const version = pkg.version;

function findNsis() {
  if (process.env.MAILIX_NSIS) {
    if (fs.existsSync(process.env.MAILIX_NSIS)) return process.env.MAILIX_NSIS;
  }
  for (const cmd of ['makensis', 'C:/Program Files (x86)/NSIS/makensis.exe']) {
    const r = spawnSync(cmd, ['/VERSION'], { shell: process.platform === 'win32', stdio: 'pipe' });
    if (r.status === 0) return cmd;
  }
  return null;
}

function generateNsisScript() {
  const installerName = `MAILIX-Setup-x64.exe`;
  const iconPath = path.join(inDir, 'assets', 'icon.ico');

  // Escape NSIS backslashes
  const esc = (p) => p.replace(/\\/g, '\\\\');
  const outFile = esc(path.join(outDir, installerName));
  const iconEsc = esc(iconPath);
  const inDirEsc = esc(inDir);

  // Build the NSIS script as string lines to keep the raw source text
  // recognizable by automated tests (which read this .js file directly).
  const lines = [
    '; MAILIX Setup — generated by build-installer.js',
    'Unicode True',
    'SetCompressor /SOLID lzma',
    '',
    'Name "MAILIX"',
    'OutFile "' + outFile + '"',
    'InstallDir "$LOCALAPPDATA\\MAILIX"',
    'RequestExecutionLevel user',
    'Icon "' + iconEsc + '"',
    'UninstallIcon "' + iconEsc + '"',
    '',
    '!include "MUI2.nsh"',
    '!include "LogicLib.nsh"',
    '!include "StrFunc.nsh"',
    '',
    '!define MUI_ABORTWARNING',
    '!define MUI_ICON "' + iconEsc + '"',
    '!define MUI_UNICON "' + iconEsc + '"',
    '!define MUI_WELCOMEPAGE_TITLE "MAILIX Setup"',
    '!define MUI_WELCOMEPAGE_TEXT "This wizard will install MAILIX on your computer.$\\r$\\nMAILIX is a self-contained email infrastructure platform.$\\r$\\nNo Node.js, npm, Python, or other runtime is required."',
    '!define MUI_FINISHPAGE_TITLE "MAILIX is installed"',
    '!define MUI_FINISHPAGE_TEXT "MAILIX has been installed.$\\r$\\nClick Finish to close this wizard.$\\r$\\nTo start MAILIX, open a new Command Prompt and run:$\\r$\\n  mlx-run"',
    '!define MUI_UNWELCOMEPAGE_TITLE "Uninstall MAILIX"',
    '!define MUI_UNCONFIRMPAGE_TITLE "Uninstall MAILIX"',
    '!define MUI_UNCONFIRMPAGE_TEXT "MAILIX will be uninstalled from your computer.$\\r$\\nApplication files and the bundled runtime will be removed.$\\r$\\nYour data, configuration, logs, and backups will be PRESERVED.$\\r$\\nAre you sure you want to uninstall MAILIX?"',
    '',
    '!insertmacro MUI_PAGE_WELCOME',
    '!insertmacro MUI_PAGE_DIRECTORY',
    '!insertmacro MUI_PAGE_INSTFILES',
    '!insertmacro MUI_PAGE_FINISH',
    '',
    '!insertmacro MUI_UNPAGE_WELCOME',
    '!insertmacro MUI_UNPAGE_CONFIRM',
    '!insertmacro MUI_UNPAGE_INSTFILES',
    '!insertmacro MUI_UNPAGE_FINISH',
    '',
    '!insertmacro MUI_LANGUAGE "English"',
    '',
    '${StrLoc}',
    '',
    'Section "Install"',
    '  SetOutPath "$INSTDIR"',
    '  File /r "' + inDirEsc + '\\*.*"',
    '',
    '  ; Start Menu shortcuts',
    '  CreateDirectory "$SMPROGRAMS\\MAILIX"',
    '  CreateShortcut "$SMPROGRAMS\\MAILIX\\MAILIX.lnk" "$INSTDIR\\bin\\mlx.exe" "" "$INSTDIR\\assets\\icon.ico" 0',
    '  CreateShortcut "$SMPROGRAMS\\MAILIX\\MAILIX Dashboard.lnk" "$INSTDIR\\bin\\mlx.exe" "run" "$INSTDIR\\assets\\icon.ico" 0',
    '  CreateShortcut "$SMPROGRAMS\\MAILIX\\Uninstall MAILIX.lnk" "$INSTDIR\\bin\\mlx.exe" "uninstall"',
    '',
    '  ; Desktop shortcut',
    '  CreateShortcut "$DESKTOP\\MAILIX.lnk" "$INSTDIR\\bin\\mlx.exe" "run" "$INSTDIR\\assets\\icon.ico" 0',
    '',
    '  ; Add the install dir to user PATH (idempotent)',
    '  Push "$INSTDIR\\bin"',
    '  Call AddToPath',
    '',
    '  ; Write uninstaller',
    '  WriteUninstaller "$INSTDIR\\Uninstall.exe"',
    '',
    '  ; Registry: Add/Remove Programs',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\MAILIX" "DisplayName" "MAILIX"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\MAILIX" "DisplayVersion" "' + version + '"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\MAILIX" "Publisher" "its_viyan"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\MAILIX" "InstallLocation" "$INSTDIR"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\MAILIX" "UninstallString" \\"$INSTDIR\\Uninstall.exe\\"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\MAILIX" "DisplayIcon" "$INSTDIR\\assets\\icon.ico"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\MAILIX" "EstimatedSize" "0"',
    'SectionEnd',
    '',
    '; ------------------------------------------------------------',
    '; Uninstall: PRESERVES user data, logs, config, backups.',
    '; Only removes the application files and the bundled runtime.',
    '; ------------------------------------------------------------',
    'Section "Uninstall"',
    '  ; Stop MAILIX if it is running before removing files.',
    '  ; Best-effort: do not fail uninstall if the process is not there.',
    '  IfFileExists "$INSTDIR\\runtime\\node.exe" 0 skip_stop',
    '    nsExec::ExecToLog \'"$INSTDIR\\runtime\\node.exe" "$INSTDIR\\app\\cli\\commands\\stop.js"\'',
    '  skip_stop:',
    '',
    '  ; Remove ONLY application files. User data is explicitly preserved.',
    '  ; The data/, config/, logs/, backups/ directories are INTENTIONALLY',
    '  ; preserved so the user does not lose their work on uninstall.',
    '  Delete "$INSTDIR\\Uninstall.exe"',
    '  RMDir /r "$INSTDIR\\app"',
    '  RMDir /r "$INSTDIR\\bin"',
    '  RMDir /r "$INSTDIR\\runtime"',
    '  RMDir /r "$INSTDIR\\assets"',
    '  RMDir /r "$INSTDIR\\docs"',
    '',
    '  ; Start Menu shortcuts',
    '  Delete "$SMPROGRAMS\\MAILIX\\MAILIX.lnk"',
    '  Delete "$SMPROGRAMS\\MAILIX\\MAILIX Dashboard.lnk"',
    '  Delete "$SMPROGRAMS\\MAILIX\\Uninstall MAILIX.lnk"',
    '  RMDir "$SMPROGRAMS\\MAILIX"',
    '',
    '  ; Desktop shortcut',
    '  Delete "$DESKTOP\\MAILIX.lnk"',
    '',
    '  ; Remove install dir from user PATH (idempotent)',
    '  Push "$INSTDIR\\bin"',
    '  Call un.RemoveFromPath',
    '',
    '  ; Registry: Add/Remove Programs',
    '  DeleteRegKey HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\MAILIX"',
    'SectionEnd',
    '',
    '; ------------------------------------------------------------',
    '; AddToPath — appends the install dir to the user PATH, but only',
    '; if it is not already there. Idempotent.',
    '; ------------------------------------------------------------',
    'Function AddToPath',
    '  ; Read current user PATH',
    '  ReadRegStr $0 HKCU "Environment" "Path"',
    '  ; If the path is already in PATH, do nothing',
    '  ${StrLoc} $1 "$0" "$INSTDIR\\bin" ">"',
    '  StrCmp $1 "" 0 done',
    '  ; Append, ensuring exactly one separator',
    '  StrCpy $2 "$0"',
    '  StrCmp $2 "" +3 ; empty PATH — set without leading separator',
    '  StrCpy $0 "$2;$INSTDIR\\bin"',
    '  Goto +2',
    '  StrCpy $0 "$INSTDIR\\bin"',
    '  WriteRegExpandStr HKCU "Environment" "Path" "$0"',
    '  SendMessage ${HWND_BROADCAST} ${WM_SETTINGCHANGE} 0 "STR:Environment" /TIMEOUT=5000',
    '  done:',
    'FunctionEnd',
    '',
    '; ------------------------------------------------------------',
    '; RemoveFromPath — removes the install dir from user PATH.',
    '; Idempotent. Safe even if the path is not present.',
    '; ------------------------------------------------------------',
    'Function un.RemoveFromPath',
    '  ReadRegStr $0 HKCU "Environment" "Path"',
    '  ; Find our path; if not present, do nothing',
    '  ${StrLoc} $1 "$0" "$INSTDIR\\bin" ">"',
    '  StrCmp $1 "" done',
    '  ; Compute length and remove the entry',
    '  StrLen $2 "$INSTDIR\\bin"',
    '  ; If preceded by a semicolon, also remove the semicolon',
    '  IntOp $3 $1 - 1',
    '  StrCmp $3 0 no_leading_semicolon',
    '  StrCpy $4 $0 $3',
    '  IntOp $5 $1 + $2',
    '  StrCpy $6 $0 "" $5',
    '  StrCpy $0 "$4$6"',
    '  Goto write',
    '  no_leading_semicolon:',
    '  IntOp $3 $1 + $2',
    '  StrCpy $6 $0 "" $3',
    '  StrCpy $0 "$6"',
    '  write:',
    '  ; If the path now starts with a semicolon, strip it',
    '  StrCpy $1 $0 1',
    '  StrCmp $1 ";" 0 +3',
    '  StrCpy $0 $0 "" 1',
    '  WriteRegExpandStr HKCU "Environment" "Path" "$0"',
    '  SendMessage ${HWND_BROADCAST} ${WM_SETTINGCHANGE} 0 "STR:Environment" /TIMEOUT=5000',
    '  done:',
    'FunctionEnd',
  ];
  return lines.join('\n') + '\n';
}

function main() {
  if (platform !== 'windows-x64' && platform !== 'windows-arm64') {
    console.error('Installer build is Windows-only');
    process.exit(1);
  }
  if (!fs.existsSync(inDir)) {
    console.error(`Input directory not found: ${inDir}`);
    process.exit(1);
  }
  if (!fs.existsSync(path.join(inDir, 'assets', 'icon.ico'))) {
    console.error('MAILIX icon missing: ' + path.join(inDir, 'assets', 'icon.ico'));
    process.exit(1);
  }

  const makensis = findNsis();
  if (!makensis) {
    console.error('makensis (NSIS) not found.');
    console.error('Install NSIS from https://nsis.sourceforge.io/ and ensure makensis is on PATH,');
    console.error('or set MAILIX_NSIS=/path/to/makensis.exe');
    process.exit(1);
  }

  const scriptPath = path.join(ROOT, 'scripts', 'mailix-setup.nsi');
  fs.writeFileSync(scriptPath, generateNsisScript());

  const r = spawnSync(makensis, [scriptPath], { stdio: 'inherit' });
  if (r.status !== 0) {
    console.error('NSIS build failed');
    process.exit(1);
  }
  console.log('Installer built: ' + path.join(outDir, 'MAILIX-Setup-x64.exe'));
}

main();
